"""Калькулятор доклада. Все допущения вынесены наверх; меняйте их под свой регион.

Проверенные входные данные — презентация НИУ ВШЭ «Разработка финансово-экономической модели
сопровождаемого проживания…» (2022): затраты на одного проживающего в месяц, включая личные расходы,
ПНИ — 44,8 тыс. ₽, проекты сопровождаемого проживания — 52,9 тыс. ₽ (столица — 111,9).
Ориентир для цены часа: тарифы Москвы на социальное обслуживание на дому, 2026 — 507 ₽ (основные
услуги) и 337 ₽ (дополнительные). Остальное — рабочие допущения автора; они помечены ASSUMPTION.
"""

# ---- проверенные данные
C_PNI = 44.8          # тыс. ₽/мес, текущие расходы на человека в ПНИ (ВШЭ)
C_SP = 52.9           # тыс. ₽/мес, проекты сопровождаемого проживания (ВШЭ)
C_SP_MSK = 111.9      # тыс. ₽/мес, то же в Москве (ВШЭ)
WEEKS_PER_MONTH = 52 / 12

GDP_2024 = 201_000          # млрд ₽, ВВП России 2024 (Росстат, округлённо; источник в тексте доклада не сверялся)

# ---- индексация цен (Банк России, годовая инфляция в декабре, % г/г; cbr.ru/hd_base/infl, прочитано 19.10.2026)
CPI_DEC = {2020: 4.90, 2021: 8.39, 2022: 11.94, 2023: 7.42, 2024: 9.52, 2025: 5.59}


def price_index(from_year, to_year=2025):
    """Во сколько раз выросли цены с декабря from_year по декабрь to_year (по ИПЦ)."""
    k = 1.0
    for y in range(from_year + 1, to_year + 1):
        k *= 1 + CPI_DEC[y] / 100
    return k


# ASSUMPTION: 44,8 — в ценах 2019 года (данные обследования НИИ труда 2019), 52,9 — в ценах 2021 года
# (опрос проектов ВШЭ 2021). В презентации ВШЭ год цен не указан; если ВШЭ уже индексировала цифры,
# индексация здесь завышает их.
PNI_PRICE_YEAR, SP_PRICE_YEAR = 2019, 2021
C_PNI_2025 = C_PNI * price_index(PNI_PRICE_YEAR)
C_SP_2025 = C_SP * price_index(SP_PRICE_YEAR)

# ---- допущения (ASSUMPTION)
HOUR_PRICE = (350, 475, 600)     # ₽ за час сопровождения: низ / база / верх
LIVING_FIXED = (22, 30, 38)      # тыс. ₽/мес на жильё и быт (аренда доли квартиры, коммуналка, еда, одежда)


def flat_cost(hours_per_week, hour_price, fixed):
    """Полная стоимость жизни в квартире, тыс. ₽/мес: сопровождение + жильё и быт."""
    support = hours_per_week * WEEKS_PER_MONTH * hour_price / 1000
    return support + fixed


def breakeven_hours(hour_price, fixed, pni=None):
    """Сколько часов в неделю можно оплатить, чтобы уложиться в стоимость места в ПНИ."""
    pni = C_PNI if pni is None else pni
    return (pni - fixed) * 1000 / hour_price / WEEKS_PER_MONTH


def per_million():
    """Сколько единиц услуги покупает 1 млн ₽ в год."""
    year = 1000  # тыс. ₽
    return {
        "Место в ПНИ (44,8 тыс. ₽/мес)": year / (C_PNI * 12),
        "Сопровождаемое проживание (52,9)": year / (C_SP * 12),
        "Сопровождаемое проживание, столица (111,9)": year / (C_SP_MSK * 12),
        "Часы сопровождения, по 350 ₽": 1_000_000 / 350,
        "Часы сопровождения, по 600 ₽": 1_000_000 / 600,
    }


def report_indexed():
    print("\n== В ценах 2025 года (ИПЦ, Банк России)")
    print(f"  индекс 2019→2025: {price_index(2019):.3f}; 2021→2025: {price_index(2021):.3f}")
    print(f"  ПНИ: {C_PNI} → {C_PNI_2025:.1f} тыс. ₽/мес; СП: {C_SP} → {C_SP_2025:.1f}; столица: {C_SP_MSK} → {C_SP_MSK*price_index(2021):.1f}")
    print("  точка безубыточности, ч/нед (оптимист / база / пессимист):",
          [round(breakeven_hours(p, f, C_PNI_2025), 1) for p, f in ((350, 22), (475, 30), (600, 38))])
    light = 80
    for name, p, f in (("оптимист", 350, 22), ("база", 475, 30), ("пессимист", 600, 38)):
        c = flat_cost(12, p, f)
        print(f"  {name}: квартира {c:.1f}; разница на {light} чел. {light*(c-C_PNI_2025)*12/1000:+.1f} млн ₽/год")
    print(f"  регион N: 400 × {C_PNI_2025:.1f} × 12 = {400*C_PNI_2025*12/1000:.1f} млн ₽/год")
    print(f"  1 млн ₽: {1000/(C_PNI_2025*12):.2f} места в ПНИ; {1000/(C_SP_2025*12):.2f} чел. в СП")


if __name__ == "__main__":
    report_indexed()
    print("== 1 млн ₽ в год покупает")
    for k, v in per_million().items():
        print(f"  {k}: {v:,.2f}")

    print("\n== Полная стоимость жизни в квартире, тыс. ₽/мес (ПНИ = 44,8)")
    for h in (6, 12, 24, 40):
        row = []
        for lo, hi in zip((HOUR_PRICE[0], HOUR_PRICE[1], HOUR_PRICE[2]), (LIVING_FIXED[0], LIVING_FIXED[1], LIVING_FIXED[2])):
            row.append(round(flat_cost(h, lo, hi), 1))
        print(f"  {h:>2} ч/нед: низ {row[0]}  база {row[1]}  верх {row[2]}")

    print("\n== Точка безубыточности, ч/нед")
    for name, p, f in (("оптимист", HOUR_PRICE[0], LIVING_FIXED[0]), ("база", HOUR_PRICE[1], LIVING_FIXED[1]), ("пессимист", HOUR_PRICE[2], LIVING_FIXED[2])):
        print(f"  {name}: {breakeven_hours(p, f):.1f}")

    # Регион N
    places = 400
    total = places * C_PNI * 12 / 1000
    print(f"\n== Регион N: {places} мест × {C_PNI} × 12 = {total:.1f} млн ₽/год")
    light = round(places * 0.20)   # доля нижегородского обследования: каждый пятый, ≤ 12 ч/нед
    print(f"  «лёгкая» когорта (20%): {light} чел.")
    for name, p, f in (("оптимист", 350, 22), ("база", 475, 30), ("пессимист", 600, 38)):
        c = flat_cost(12, p, f)
        delta = light * (c - C_PNI) * 12 / 1000
        print(f"  {name}: квартира {c:.1f} тыс./мес на чел.; разница с ПНИ {delta:+.1f} млн ₽/год на {light} чел.")
    mid = round(places * 0.25)
    print(f"  «средняя» когорта до 45% (ещё {mid} чел.) в СП по ВШЭ: {mid*(C_SP-C_PNI)*12/1000:+.1f} млн ₽/год относительно ПНИ")
    print(f"  Вариант столицы для СП для {mid} чел.: {mid*(C_SP_MSK-C_PNI)*12/1000:+.1f} млн ₽/год")

    # Масштаб страны
    resid = 139_000
    print(f"\n== Страна: 45% от {resid:,} = {0.45*resid:,.0f} чел.; 200–300 млрд ₽ на ПНИ = {200e9/resid/1e6:.2f}–{300e9/resid/1e6:.2f} млн ₽ на жителя")
    pni_total = resid * C_PNI * 12 / 1e6  # млрд ₽
    print(f"  Расходы на все ПНИ: {resid:,} × {C_PNI} × 12 = {pni_total:.1f} млрд ₽ = {pni_total/GDP_2024*100:.3f} % ВВП 2024")
